package com.practicum.mateocare.ai.prompts

import com.practicum.mateocare.ai.prompts.model.StatusInput


class StatusPromptBuilder : PromptBuilder<StatusInput> {

    override fun build(input: StatusInput): String {
        return """
Ты медицинско-метеорологический аналитический модуль.

Твоя задача — определить степень метеочувствительности человека на основе его ответов и составить общий совет по его состоянию.

Верни ТОЛЬКО JSON:

{
  "meteoStatus": {
    "type": "",
    "level": "low | medium | high",
    "score": 0
  },
  "advice": ""
}

ЯЗЫК ОТВЕТА:
- отвечай ТОЛЬКО на русском языке
- поле "type" должно быть на русском языке
- level строго: low | medium | high (не переводить)

ПРАВИЛА:
- score от 0 до 100
- type = краткий тип метеочувствительности:
  (например: "гипертонический тип", "гипотонический тип", "суставной тип", "мигренозный тип", "слабовыраженный")
- учитывай возраст пользователя
- advice должен описывать чем характеризуется тип метеочутсвительности пользователя, какие симптомы включает и как можно улучшить самочуствие
- advice должен составлять 4-5 предложений
- в advice дели текст на абзацы

ПОЛЬЗОВАТЕЛЬ:
Возраст: ${input.age}

ОТВЕТЫ НА АНКЕТУ:
${input.answers}

ИНСТРУКЦИЯ:
- анализируй симптомы и частоту реакций на погоду
- оценивай силу влияния погоды на организм
- не ставь медицинские диагнозы

Верни только JSON:
""".trimIndent()
    }
}